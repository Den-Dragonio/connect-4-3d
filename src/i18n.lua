function I18N.t(key, ...)
    local dict = I18N.strings[I18N.current] or I18N.strings.en
    local val = dict[key] or I18N.strings.en[key] or key
    if select("#", ...) > 0 then
        return string.format(val, ...)
    end
    return val
end

return I18N
